// Generates src/speech/woof/kernels.wat (WebAssembly SIMD kernels for the Woof voice) and compiles it into
// src/speech/woof/kernels.ts as base64. Run with: npx -y -p wabt@1.0.36 node scripts/build-woof-kernels.mjs
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const dir = new URL("../src/speech/woof/", import.meta.url);

const get = (name) => `(local.get $${name})`;
const add = (a, b) => `(i32.add ${a} ${b})`;
const shl2 = (a) => `(i32.shl ${a} (i32.const 2))`;

/** A tile of `rows` rows x `vectors` four-float columns: out += A @ B for that tile, accumulating in registers. */
function tile(rows, vectors) {
  const lines = [`(local.set $po ${add(get("prow"), shl2(get("c")))})`];
  for (let j = 0; j < rows; j++) {
    for (let v = 0; v < vectors; v++) lines.push(`(local.set $x${j}${v} (v128.load offset=${v * 16} ${add(get("po"), `(i32.mul (i32.const ${j}) ${get("nb")})`)}))`);
  }
  lines.push(`(local.set $pb ${add(get("b"), shl2(get("c")))})`, "(local.set $i (i32.const 0))");
  const body = [`(br_if $kdone (i32.ge_s ${get("i")} ${get("k")}))`, "(local.set $b0 (v128.load (local.get $pb)))"];
  if (vectors === 2) body.push("(local.set $b1 (v128.load offset=16 (local.get $pb)))");
  for (let j = 0; j < rows; j++) {
    body.push(`(local.set $s (f32x4.splat (f32.load ${add(get(`pa${j}`), shl2(get("i")))})))`);
    for (let v = 0; v < vectors; v++) body.push(`(local.set $x${j}${v} (f32x4.add (local.get $x${j}${v}) (f32x4.mul (local.get $s) (local.get $b${v}))))`);
  }
  body.push(`(local.set $pb ${add(get("pb"), get("nb"))})`, `(local.set $i ${add(get("i"), "(i32.const 1)")})`, "(br $kloop)");
  lines.push(`(block $kdone (loop $kloop\n        ${body.join("\n        ")}))`);
  for (let j = 0; j < rows; j++) {
    for (let v = 0; v < vectors; v++) lines.push(`(v128.store offset=${v * 16} ${add(get("po"), `(i32.mul (i32.const ${j}) ${get("nb")})`)} (local.get $x${j}${v}))`);
  }
  return lines.join("\n      ");
}

/** One column at a time, for the few layers whose width is not a multiple of four. */
function scalar(rows) {
  const lines = [];
  for (let j = 0; j < rows; j++) {
    lines.push(
      `(local.set $po ${add(add(get("prow"), `(i32.mul (i32.const ${j}) ${get("nb")})`), shl2(get("c")))})`,
      "(local.set $acc (f32.load (local.get $po)))",
      `(local.set $pb ${add(get("b"), shl2(get("c")))})`,
      "(local.set $i (i32.const 0))",
      `(block $sdone${j} (loop $sloop${j}
        (br_if $sdone${j} (i32.ge_s ${get("i")} ${get("k")}))
        (local.set $acc (f32.add (local.get $acc) (f32.mul (f32.load ${add(get(`pa${j}`), shl2(get("i")))}) (f32.load (local.get $pb)))))
        (local.set $pb ${add(get("pb"), get("nb"))})
        (local.set $i ${add(get("i"), "(i32.const 1)")})
        (br $sloop${j})))`,
      "(f32.store (local.get $po) (local.get $acc))"
    );
  }
  return lines.join("\n      ");
}

function columns(rows, label) {
  return `(local.set $c (i32.const 0))
    (block $c8done${label} (loop $c8${label}
      (br_if $c8done${label} (i32.gt_s ${add(get("c"), "(i32.const 8)")} ${get("n")}))
      ${tile(rows, 2)}
      (local.set $c ${add(get("c"), "(i32.const 8)")})
      (br $c8${label})))
    (block $c4done${label} (loop $c4${label}
      (br_if $c4done${label} (i32.gt_s ${add(get("c"), "(i32.const 4)")} ${get("n")}))
      ${tile(rows, 1)}
      (local.set $c ${add(get("c"), "(i32.const 4)")})
      (br $c4${label})))
    (block $c1done${label} (loop $c1${label}
      (br_if $c1done${label} (i32.ge_s ${get("c")} ${get("n")}))
      ${scalar(rows)}
      (local.set $c ${add(get("c"), "(i32.const 1)")})
      (br $c1${label})))`;
}

const locals = ["r", "c", "i", "pa0", "pa1", "pa2", "pa3", "pb", "po", "prow", "nb", "lb"].map((name) => `(local $${name} i32)`).join(" ");
const vectors = ["b0", "b1", "s", "x00", "x01", "x10", "x11", "x20", "x21", "x30", "x31"].map((name) => `(local $${name} v128)`).join(" ");

const wat = `;; Generated by scripts/build-woof-kernels.mjs. WebAssembly SIMD kernels for the Underdog Woof voice.
(module
  (import "env" "memory" (memory 1))

  ;; out (t x n, row stride n) += A (t x k, row stride lda) @ B (k x n), all float32, in tiles of 4 rows x 8 columns.
  (func (export "gemm") (param $a i32) (param $lda i32) (param $t i32) (param $k i32) (param $b i32) (param $n i32) (param $out i32)
    ${locals} ${vectors} (local $acc f32)
    (local.set $nb ${shl2(get("n"))})
    (local.set $lb ${shl2(get("lda"))})
    (local.set $r (i32.const 0))
    (block $r4done (loop $r4
      (br_if $r4done (i32.gt_s ${add(get("r"), "(i32.const 4)")} ${get("t")}))
      (local.set $pa0 ${add(get("a"), `(i32.mul ${get("r")} ${get("lb")})`)})
      (local.set $pa1 ${add(get("pa0"), get("lb"))})
      (local.set $pa2 ${add(get("pa1"), get("lb"))})
      (local.set $pa3 ${add(get("pa2"), get("lb"))})
      (local.set $prow ${add(get("out"), `(i32.mul ${get("r")} ${get("nb")})`)})
      ${columns(4, "x4")}
      (local.set $r ${add(get("r"), "(i32.const 4)")})
      (br $r4)))
    (block $r1done (loop $r1
      (br_if $r1done (i32.ge_s ${get("r")} ${get("t")}))
      (local.set $pa0 ${add(get("a"), `(i32.mul ${get("r")} ${get("lb")})`)})
      (local.set $prow ${add(get("out"), `(i32.mul ${get("r")} ${get("nb")})`)})
      ${columns(1, "x1")}
      (local.set $r ${add(get("r"), "(i32.const 1)")})
      (br $r1))))

  ;; out[r] = W[r] . x for int8 W (rows x cols, cols a multiple of 16) and float32 x.
  (func (export "matvecI8") (param $w i32) (param $rows i32) (param $cols i32) (param $x i32) (param $out i32)
    (local $r i32) (local $c i32) (local $pw i32) (local $q v128) (local $h v128)
    (local $a0 v128) (local $a1 v128) (local $a2 v128) (local $a3 v128)
    (local.set $pw (local.get $w))
    (block $rdone (loop $rloop
      (br_if $rdone (i32.ge_s (local.get $r) (local.get $rows)))
      (local.set $a0 (v128.const i32x4 0 0 0 0))
      (local.set $a1 (v128.const i32x4 0 0 0 0))
      (local.set $a2 (v128.const i32x4 0 0 0 0))
      (local.set $a3 (v128.const i32x4 0 0 0 0))
      (local.set $c (i32.const 0))
      (block $cdone (loop $cloop
        (br_if $cdone (i32.ge_s (local.get $c) (local.get $cols)))
        (local.set $q (v128.load (i32.add (local.get $pw) (local.get $c))))
        (local.set $h (i16x8.extend_low_i8x16_s (local.get $q)))
        (local.set $a0 (f32x4.add (local.get $a0) (f32x4.mul (f32x4.convert_i32x4_s (i32x4.extend_low_i16x8_s (local.get $h)))
          (v128.load (i32.add (local.get $x) (i32.shl (local.get $c) (i32.const 2)))))))
        (local.set $a1 (f32x4.add (local.get $a1) (f32x4.mul (f32x4.convert_i32x4_s (i32x4.extend_high_i16x8_s (local.get $h)))
          (v128.load offset=16 (i32.add (local.get $x) (i32.shl (local.get $c) (i32.const 2)))))))
        (local.set $h (i16x8.extend_high_i8x16_s (local.get $q)))
        (local.set $a2 (f32x4.add (local.get $a2) (f32x4.mul (f32x4.convert_i32x4_s (i32x4.extend_low_i16x8_s (local.get $h)))
          (v128.load offset=32 (i32.add (local.get $x) (i32.shl (local.get $c) (i32.const 2)))))))
        (local.set $a3 (f32x4.add (local.get $a3) (f32x4.mul (f32x4.convert_i32x4_s (i32x4.extend_high_i16x8_s (local.get $h)))
          (v128.load offset=48 (i32.add (local.get $x) (i32.shl (local.get $c) (i32.const 2)))))))
        (local.set $c (i32.add (local.get $c) (i32.const 16)))
        (br $cloop)))
      (local.set $a0 (f32x4.add (f32x4.add (local.get $a0) (local.get $a1)) (f32x4.add (local.get $a2) (local.get $a3))))
      (f32.store (i32.add (local.get $out) (i32.shl (local.get $r) (i32.const 2)))
        (f32.add (f32.add (f32x4.extract_lane 0 (local.get $a0)) (f32x4.extract_lane 1 (local.get $a0)))
                 (f32.add (f32x4.extract_lane 2 (local.get $a0)) (f32x4.extract_lane 3 (local.get $a0)))))
      (local.set $pw (i32.add (local.get $pw) (local.get $cols)))
      (local.set $r (i32.add (local.get $r) (i32.const 1)))
      (br $rloop))))

  ;; out[r] = W[r] . x for float32 W (rows x cols, cols a multiple of 4).
  (func (export "matvecF32") (param $w i32) (param $rows i32) (param $cols i32) (param $x i32) (param $out i32)
    (local $r i32) (local $c i32) (local $pw i32) (local $a0 v128)
    (local.set $pw (local.get $w))
    (block $rdone (loop $rloop
      (br_if $rdone (i32.ge_s (local.get $r) (local.get $rows)))
      (local.set $a0 (v128.const i32x4 0 0 0 0))
      (local.set $c (i32.const 0))
      (block $cdone (loop $cloop
        (br_if $cdone (i32.ge_s (local.get $c) (local.get $cols)))
        (local.set $a0 (f32x4.add (local.get $a0) (f32x4.mul
          (v128.load (i32.add (local.get $pw) (i32.shl (local.get $c) (i32.const 2))))
          (v128.load (i32.add (local.get $x) (i32.shl (local.get $c) (i32.const 2)))))))
        (local.set $c (i32.add (local.get $c) (i32.const 4)))
        (br $cloop)))
      (f32.store (i32.add (local.get $out) (i32.shl (local.get $r) (i32.const 2)))
        (f32.add (f32.add (f32x4.extract_lane 0 (local.get $a0)) (f32x4.extract_lane 1 (local.get $a0)))
                 (f32.add (f32x4.extract_lane 2 (local.get $a0)) (f32x4.extract_lane 3 (local.get $a0)))))
      (local.set $pw (i32.add (local.get $pw) (i32.shl (local.get $cols) (i32.const 2))))
      (local.set $r (i32.add (local.get $r) (i32.const 1)))
      (br $rloop)))))
`;

writeFileSync(new URL("kernels.wat", dir), wat);
const wabt = await require("wabt")();
const module = wabt.parseWat("kernels.wat", wat, { simd: true });
module.validate();
const { buffer } = module.toBinary({});
writeFileSync(new URL("kernels.ts", dir), `// Generated by scripts/build-woof-kernels.mjs from kernels.wat. Do not edit.
export const kernelsWasm = "${Buffer.from(buffer).toString("base64")}";
`);
console.log(`kernels.wasm: ${buffer.length} bytes`);
