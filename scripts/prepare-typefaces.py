"""Rebuild local CSS and static subtitle faces from the bundled Google Fonts sources.

Contributor-only dependency: fonttools. Application builds do not run this script.
The upstream SIL Open Font Licenses remain alongside every font family.
"""
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[1] / "src/assets/fonts"
FAMILIES = {
    "readex-pro": "Readex Pro", "lexend": "Lexend",
    "atkinson-hyperlegible-next": "Atkinson Hyperlegible Next",
    "atkinson-hyperlegible-mono": "Atkinson Hyperlegible Mono",
    "andika": "Andika", "noto-sans": "Noto Sans",
    "source-sans-3": "Source Sans 3", "ibm-plex-mono": "IBM Plex Mono",
    "jetbrains-mono": "JetBrains Mono",
}

rules = ["/* Generated by scripts/prepare-typefaces.py. Fonts are served locally. */"]
for slug, family in FAMILIES.items():
    for suffix, style, weight in [
        ("variable", "normal", None), ("italic-variable", "italic", None),
        ("regular", "normal", 400), ("bold", "normal", 700),
        ("italic", "italic", 400), ("bolditalic", "italic", 700),
    ]:
        path = ROOT / f"{slug}-{suffix}.ttf"
        if not path.exists():
            continue
        font = TTFont(path)
        if weight is None:
            axis = next(axis for axis in font["fvar"].axes if axis.axisTag == "wght")
            weights = f"{axis.minValue:g} {axis.maxValue:g}"
        else:
            weights = str(weight)
        rules.append(f"""@font-face {{
  font-family: '{family}';
  font-style: {style};
  font-weight: {weights};
  font-display: swap;
  src: url('./{path.name}') format('truetype');
}}""")
        if suffix == "variable":
            axes = {axis.axisTag: axis.defaultValue for axis in font["fvar"].axes}
            axes["wght"] = 700
            bold = instantiateVariableFont(font, axes, inplace=False)
            # Use the true bold instance in libass, which requests a bold face.
            for name_id, value in [(1, family), (2, "Bold"), (16, family), (17, "Bold"),
                                   (6, family.replace(" ", "") + "-Bold")]:
                bold["name"].setName(value, name_id, 3, 1, 0x409)
            bold["OS/2"].fsSelection = (bold["OS/2"].fsSelection | 32) & ~64
            bold["head"].macStyle |= 1
            bold.save(ROOT / f"{slug}-subtitle-bold.ttf")
        font.close()
    print(family)

(ROOT / "additional-fonts.css").write_text("\n\n".join(rules) + "\n", encoding="utf-8")
